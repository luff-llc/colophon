//! Lists the names a build exports by reading the sources that define them, for the test that
//! holds the UniFFI crate and the wasm crate to one list (`src/v05/surface-names.txt`).
//!
//! It reads the shared sources (`src/v05/api/*.rs`) and, for the wasm crate, its glue. It is a
//! source-level check of what the attributes select; it does not read generated bindings.
#![allow(dead_code, clippy::unwrap_used)]
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

pub fn api_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../colophon-ffi/src/v05")
        .canonicalize()
        .unwrap()
}
pub fn list_file() -> PathBuf {
    api_dir().join("surface-names.txt")
}
/// The names only the `conformance` feature exports (`api/conformance.rs`).
pub fn conformance_list_file() -> PathBuf {
    api_dir().join("surface-names-conformance.txt")
}
/// Names that must never be in a release build: each bypasses a trust boundary (an invented
/// account view, supplied epoch keys, the machine or the receiver without the endpoint).
pub const CONFORMANCE_ONLY: [&str; 6] = [
    "SessionAccountView.supplied",
    "SessionEpochs.with_keys",
    "object:SessionEpochs",
    "object:SessionMachine",
    "object:SessionWireReceiver",
    "AccountEngine.session_epochs",
];

/// Whether the attribute lines before an item export it for `feature` (`native05`/`web05`).
fn exported(window: &[String], feature: &str) -> bool {
    let (attr, plain) = if feature == "native05" {
        ("uniffi::export", "#[uniffi::export]")
    } else {
        (
            "wasm_bindgen::prelude::wasm_bindgen",
            "#[wasm_bindgen::prelude::wasm_bindgen]",
        )
    };
    let other = if feature == "native05" {
        "web05"
    } else {
        "native05"
    };
    let has = |s: &str| window.iter().any(|l| l.contains(s));
    if has(&format!("#[cfg(feature = \"{other}\")]")) {
        return false;
    }
    let by_cfg_attr = has(&format!("cfg_attr(feature = \"{feature}\", {attr}"))
        || (feature == "web05" && has("#[wasm_bindgen]"));
    let by_plain = has(&format!("#[cfg(feature = \"{feature}\")]")) && has(plain);
    by_cfg_attr || by_plain
}
fn object(window: &[String], feature: &str) -> bool {
    let k = if feature == "native05" {
        "cfg_attr(feature = \"native05\", derive(uniffi::Object))"
    } else {
        "cfg_attr(feature = \"web05\", wasm_bindgen::prelude::wasm_bindgen)"
    };
    window.iter().any(|l| l.contains(k))
}

/// `begin_*` methods generated by `begin_methods!`, records and C-like enums with their fields
/// and variants.
fn scan_macros(text: &str, out: &mut BTreeSet<String>) {
    let mut in_begin = false;
    let mut cenum: Option<(String, String)> = None;
    let mut record: Option<String> = None;
    for line in text.lines() {
        let t = line.trim_start();
        if t.starts_with("begin_methods! {")
            || t.starts_with("object_methods! {")
            || t.starts_with("object_returning! {")
        {
            in_begin = true;
            continue;
        }
        if in_begin {
            if line == "}" {
                in_begin = false;
            } else if let Some(r) = line.strip_prefix("    fn ") {
                let n = r.split('(').next().unwrap();
                out.insert(format!("AccountEngine.{n}"));
            }
            continue;
        }
        if let Some((name, body)) = cenum.as_mut() {
            if line == "}" {
                for v in body
                    .split([',', '{', '}'])
                    .map(str::trim)
                    .filter(|v| !v.is_empty())
                {
                    out.insert(format!("enum:{name}.{v}"));
                }
                cenum = None;
            } else if !t.starts_with("///") && !t.starts_with("pub enum") {
                body.push_str(t);
                body.push(',');
            } else if let Some(rest) = t.strip_prefix("pub enum ") {
                // `pub enum X { A, B }` on one line, or `pub enum X {` then one per line.
                *name = rest.split([' ', '{']).next().unwrap().to_string();
                if let Some((_, vs)) = rest.split_once('{') {
                    body.push_str(vs);
                    body.push(',');
                }
            }
            continue;
        }
        if t.starts_with("cenum! {") {
            cenum = Some((String::new(), String::new()));
            continue;
        }
        if t.starts_with("record! {") || t.starts_with("secret_record! {") {
            record = Some(String::new());
            continue;
        }
        if let Some(name) = record.as_mut() {
            if let Some(rest) = line.strip_prefix("    pub struct ") {
                *name = rest.split([' ', '{']).next().unwrap().to_string();
                out.insert(format!("record:{name}"));
            } else if let Some(rest) = line.strip_prefix("        pub ") {
                let f = rest.split(':').next().unwrap();
                out.insert(format!("record:{name}.{f}"));
            } else if line == "}" {
                record = None;
            }
        }
    }
}

fn scan_text(text: &str, feature: &str, out: &mut BTreeSet<String>) {
    scan_macros(text, out);
    let mut window: Vec<String> = Vec::new();
    let mut ty: Option<String> = None;
    let mut in_free = false;
    let mut in_error = false;
    for line in text.lines() {
        let t = line.trim_start();
        if let Some(name) = ty.as_ref().filter(|_| line.starts_with("    pub fn ")) {
            let n = line["    pub fn ".len()..]
                .split(['(', '<'])
                .next()
                .unwrap();
            out.insert(format!("{name}.{n}"));
        }
        if line == "}" {
            ty = None;
            in_free = false;
            in_error = false;
        }
        if in_free && line.starts_with("    pub fn ") {
            let n = line["    pub fn ".len()..]
                .split(['(', '<'])
                .next()
                .unwrap();
            out.insert(format!("fn:{n}"));
        }
        if in_error && line.starts_with("    ") && !line.starts_with("     ") {
            if let Some(v) = t.split([' ', '{', ',']).next() {
                if v.chars().next().is_some_and(char::is_uppercase) {
                    out.insert(format!("error:AccountError.{v}"));
                }
            }
        }
        if t.starts_with("free_fn! {") {
            in_free = true;
        }
        if t.starts_with("pub enum AccountError") {
            in_error = true;
        }
        if let Some(rest) = t.strip_prefix("impl ") {
            if exported(&window, feature) {
                let name = rest.split([' ', '{']).next().unwrap();
                ty = Some(name.to_string());
            }
            window.clear();
        } else if let Some(rest) = t.strip_prefix("pub struct ") {
            if object(&window, feature) {
                out.insert(format!(
                    "object:{}",
                    rest.split([' ', '{', ';']).next().unwrap()
                ));
            }
            window.clear();
        } else if t.starts_with("pub fn ") && exported(&window, feature) {
            let n = t["pub fn ".len()..].split(['(', '<']).next().unwrap();
            out.insert(format!("fn:{n}"));
            window.clear();
        } else if t.starts_with("#[") || t.starts_with("///") || t.starts_with("//!") {
            window.push(t.to_string());
        } else if !t.is_empty() {
            window.clear();
        }
    }
}

/// The names a build exports; `conformance` includes `api/conformance.rs`, which only the
/// `conformance` feature compiles.
pub fn scan(feature: &str, glue: Option<&Path>, conformance: bool) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let mut files: Vec<PathBuf> = std::fs::read_dir(api_dir().join("api"))
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "rs"))
        .filter(|p| conformance || !p.ends_with("conformance.rs"))
        .collect();
    files.sort();
    for f in files {
        let text = std::fs::read_to_string(&f).unwrap();
        scan_text(&text, feature, &mut out);
    }
    // The host callbacks: UniFFI's trait, a JS object's methods.
    if feature == "native05" {
        for m in ["read", "read_blob"] {
            out.insert(format!("callback:HostSource.{m}"));
        }
        out.insert("callback:SwiftTranslator.translate".to_string());
    } else if let Some(g) = glue {
        let text = std::fs::read_to_string(g).unwrap();
        let mut glue_names = BTreeSet::new();
        scan_text(&text, feature, &mut glue_names);
        out.extend(
            glue_names
                .into_iter()
                .filter(|n| !n.starts_with("AccountFault.")),
        );
        // The host callbacks are called through checked shims (`callRead`, `callReadBlob`,
        // `callTranslate`): each must be declared in the glue source.
        for (decl, name) in [
            ("fn call_read(", "callback:HostSource.read"),
            ("fn call_read_blob(", "callback:HostSource.read_blob"),
            ("fn call_translate(", "callback:SwiftTranslator.translate"),
        ] {
            if text.contains(decl) {
                out.insert(name.to_string());
            }
        }
    }
    out
}

fn read_list(path: &Path) -> BTreeSet<String> {
    std::fs::read_to_string(path)
        .unwrap()
        .lines()
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(str::to_string)
        .collect()
}
fn write_list(path: &Path, header: &str, names: &BTreeSet<String>) {
    let mut body = String::from(header);
    for n in names {
        body.push_str(n);
        body.push('\n');
    }
    std::fs::write(path, body).unwrap();
}
fn same(got: &BTreeSet<String>, want: &BTreeSet<String>, file: &str) {
    let missing: Vec<_> = want.difference(got).collect();
    let extra: Vec<_> = got.difference(want).collect();
    assert!(
        missing.is_empty() && extra.is_empty(),
        "the exported names differ from {file}\n  missing here: {missing:?}\n  not in the list: {extra:?}"
    );
}

/// The release names equal `surface-names.txt`, the names only a conformance build adds equal
/// `surface-names-conformance.txt`, and no conformance-only name is in a release build.
pub fn check(feature: &str, glue: Option<&Path>) {
    let release = scan(feature, glue, false);
    let full = scan(feature, glue, true);
    let extra: BTreeSet<String> = full.difference(&release).cloned().collect();
    for n in CONFORMANCE_ONLY {
        assert!(!release.contains(n), "{n} is in the release surface");
        if !n.starts_with("AccountEngine.") {
            assert!(extra.contains(n), "{n} is not in the conformance surface");
        }
    }
    if std::env::var("UPDATE_NAMES").is_ok() {
        write_list(
            &list_file(),
            "# The 0.5 export surface, one name per line. Both crates must produce exactly this list.\n# object:T an exported object; T.m a method or static; fn:f a free function;\n# callback:HostSource.m a host callback; error:AccountError.V an error variant.\n",
            &release,
        );
        write_list(
            &conformance_list_file(),
            "# The names only the `conformance` feature adds to the surface (`api/conformance.rs`). No\n# shipped artifact enables it; none of these may appear in surface-names.txt.\n",
            &extra,
        );
        return;
    }
    same(&release, &read_list(&list_file()), "surface-names.txt");
    same(
        &extra,
        &read_list(&conformance_list_file()),
        "surface-names-conformance.txt",
    );
}
